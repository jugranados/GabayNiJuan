const FIXTURE_URL = 'https://example.org/gabay-ni-juan-fixtures';
const RETRIEVED = '2026-09-30';
const REVIEWED = '2026-10-01';

type SourceType = 'OFFICIAL_GOVERNMENT' | 'OFFICIAL_CANDIDATE' | 'NEWS' | 'OTHER';
type VerificationStatus =
  | 'PRIMARY_SOURCE'
  | 'CORROBORATED'
  | 'SELF_DECLARED'
  | 'REPORTED'
  | 'DISPUTED'
  | 'UNVERIFIED'
  | 'OUTDATED';
type RecordType =
  'ELECTION_PARTICIPATION' | 'OFFICE_TERM' | 'AFFILIATION' | 'EDUCATION' | 'POLICY_POSITION';

const source = (
  id: string,
  title: string,
  publisher: string,
  source_type: SourceType,
  published_at: string,
  path: string | null,
  document_identifier: string | null = null,
) => ({
  id,
  title,
  publisher,
  url: path ? `${FIXTURE_URL}/${path}` : null,
  document_identifier,
  source_type,
  published_at,
  retrieved_at: RETRIEVED,
  archived_url: null,
});

const claim = (
  id: string,
  personId: string,
  recordType: RecordType,
  recordId: string,
  claimType: string,
  statement: string,
  verification_status: VerificationStatus,
  effective_from: string | null = null,
  effective_to: string | null = null,
) => ({
  id,
  subject_person_id: personId,
  subject_record_type: recordType,
  subject_record_id: recordId,
  claim_type: claimType,
  statement,
  effective_from,
  effective_to,
  verification_status,
  last_reviewed_at: REVIEWED,
});

const evidence = (
  claim_id: string,
  source_id: string,
  supports = true,
  note: string | null = null,
) => ({
  claim_id,
  source_id,
  supports,
  note,
});

