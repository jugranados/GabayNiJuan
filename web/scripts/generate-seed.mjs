#!/usr/bin/env node
/**
 * Generates ../supabase/seed.sql from the FICTIONAL development fixtures in
 * src/data/fixtures/devFixtures.ts, so the database seed and the in-app mock
 * data never drift apart.
 *
 * Usage (Node >= 22.18 / 23.6 for TypeScript type stripping):
 *   npm run seed:generate
 *
 * Fixture slugs ("person-juan-dela-cruz") become deterministic UUIDs.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { devFixtureTables } from '../src/data/fixtures/devFixtures.ts';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../../supabase/seed.sql');

const ID_COLUMNS = new Set([
  'id',
  'person_id',
  'election_id',
  'office_id',
  'organization_id',
  'subject_person_id',
  'subject_record_id',
  'claim_id',
  'source_id',
]);

/** Insert order respects foreign keys; claims are inserted before their evidence. */
const INSERT_ORDER = [
  'people',
  'elections',
  'offices',
  'political_organizations',
  'election_offices',
  'sources',
  'election_participations',
  'office_terms',
  'affiliation_records',
  'education_records',
  'award_records',
  'policy_position_records',
  'claims',
  'claim_evidence',
];

/** Publish order: everything a row references must be published first. */
const PUBLISH_ORDER = INSERT_ORDER.filter((table) => table !== 'claim_evidence');

export function fixtureUuid(slug) {
  const hex = createHash('md5').update(`gabay-ni-juan-fixture:${slug}`).digest('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`;
}

function literal(column, value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  const text = ID_COLUMNS.has(column) ? fixtureUuid(value) : value;
  return `'${String(text).replace(/'/g, "''")}'`;
}

// election_offices: any conflict, including the (election_id, office_id) pair. A database
// upgraded by 20261016090100_election_foundation already holds backfilled pairs under other ids.
const CONFLICT_TARGET = { claim_evidence: ' (claim_id, source_id)', election_offices: '' };

/**
 * Idempotent: rows that already exist are left untouched, so the seed can be
 * re-run to add new fixtures to a database that was seeded earlier.
 */
function insertStatement(table, rows) {
  const columns = [...new Set(rows.flatMap((row) => Object.keys(row)))];
  const values = rows.map(
    (row) => `  (${columns.map((column) => literal(column, row[column])).join(', ')})`,
  );
  const target = CONFLICT_TARGET[table] ?? ' (id)';
  return `insert into public.${table} (${columns.join(', ')}) values\n${values.join(',\n')}\non conflict${target} do nothing;`;
}

/**
 * A database upgraded by 20261016090100_election_foundation holds backfilled election offices
 * (other ids, display order 100) for pairs the fixtures also define, and the insert above skips
 * them. Give those pairs the fixture display order, so an upgraded and a fresh database show the
 * same order. Changes nothing on a re-run.
 */
function alignElectionOfficeOrder(rows) {
  const values = rows
    .map((row) => `  (${literal('election_id', row.election_id)}::uuid, ${literal('office_id', row.office_id)}::uuid, ${row.sort_order})`)
    .join(',\n');
  return `update public.election_offices eo set sort_order = v.sort_order from (values\n${values}\n) as v(election_id, office_id, sort_order)\nwhere eo.election_id = v.election_id and eo.office_id = v.office_id and eo.sort_order <> v.sort_order;`;
}

const allFixtureIds = [];
const body = [];

for (const table of INSERT_ORDER) {
  const rows = devFixtureTables[table] ?? [];
  if (rows.length === 0) continue;
  body.push(`-- ${table}`, insertStatement(table, rows), '');
  if (table === 'election_offices') body.push(alignElectionOfficeOrder(rows), '');
  if (table !== 'claim_evidence') {
    allFixtureIds.push(...rows.map((row) => fixtureUuid(row.id)));
  }
}

body.push('-- Publish in dependency order (triggers enforce this order).');
for (const table of PUBLISH_ORDER) {
  const rows = devFixtureTables[table] ?? [];
  if (rows.length === 0) continue;
  const ids = rows.map((row) => `'${fixtureUuid(row.id)}'`).join(', ');
  body.push(
    `update public.${table} set publication_status = 'PUBLISHED' where id in (${ids}) and publication_status <> 'PUBLISHED';`,
  );
}

const idList = allFixtureIds.map((id) => `'${id}'`).join(', ');
const sql = `-- GENERATED by web/scripts/generate-seed.mjs from web/src/data/fixtures/devFixtures.ts.
-- Do not edit by hand. Regenerate with: cd web && npm run seed:generate
--
-- FICTIONAL development data only. Every person, office, organization,
-- election, and source is invented. For local / development databases ONLY.
-- Safe to re-run: existing rows are skipped and only new fixtures are added.
-- Never run this against a database that holds real records.

begin;

do $$
begin
  if exists (
    select 1 from public.people
    where publication_status = 'PUBLISHED' and id not in (${idList})
  ) then
    raise exception 'Refusing to seed: this database already holds non-fixture published people';
  end if;
end
$$;

select set_config('gnj.change_reason', 'Development seed: fictional fixtures', true);

${body.join('\n')}

commit;
`;

if (process.argv.includes('--check')) {
  // CI: fail if the committed seed is not exactly what the fixtures generate.
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== sql) {
    console.error('supabase/seed.sql is out of date. Run: cd web && npm run seed:generate');
    process.exit(1);
  }
  console.log('supabase/seed.sql is up to date.');
} else {
  writeFileSync(outFile, sql);
  console.log(`Wrote ${outFile}`);
}
